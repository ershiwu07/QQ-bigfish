/**
 * 把一个 face 编号翻成可读文字（含方括号，方便直接拼进聊天文本）。
 * @param {string|number} id
 * @returns {string} 例如 '[偷笑]'；未知编号退化成 '[QQ表情123]'
 */
export function faceTag(id) {
  const n = Number.parseInt(String(id ?? '').replace(/[^0-9]/g, ''), 10);
  if (!Number.isFinite(n)) return '[QQ表情]';
  const name = FACE_NAMES[n];
  return name ? `[${name}]` : `[QQ表情${n}]`;
}

/** 这个编号是否有名字（用于统计命中率、便于以后补表）。 */
export function faceKnown(id) {
  const n = Number.parseInt(String(id ?? '').replace(/[^0-9]/g, ''), 10);
  return Number.isFinite(n) && Boolean(FACE_NAMES[n]);
}

/**
 * 优先用 NapCat 自己带的名字。
 *
 * 为什么需要：QQ 新式大表情的 id 会到 300+（例如 id=344 是「大怨种」），
 * 静态表永远追不上。而数组格式的 face 段里带着
 *   data.raw.faceText = "/大怨种"
 *   data.raw.faceType = 2   （2 表示大表情/表情包类）
 * 直接用这个名字，比任何表都准。
 *
 * @param {string|number} id
 * @param {string} faceText NapCat 给的名字，可能带前导斜杠
 * @param {boolean} big 是否大表情（faceType=2）
 */
export function faceTagFrom(id, faceText, big = false) {
  const name = String(faceText ?? '')
    .replace(/^\//, '')
    .trim();
  if (name) return big ? `[大表情:${name}]` : `[${name}]`;
  return faceTag(id);
}
